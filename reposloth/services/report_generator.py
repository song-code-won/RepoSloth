"""Report generator service producing downloadable Markdown summaries, audit notes, and exports."""

from __future__ import annotations
from datetime import datetime
from typing import Dict, Any, List


class ReportGenerator:
    """Formats repository scan data and AI analysis into exportable Markdown reports."""

    @staticmethod
    def generate_overview_report(scan_result: Dict[str, Any], ai_overview: str) -> str:
        """Assembles a full Markdown export of the repository analysis."""
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        repo_name = scan_result.get("repo_name", "Repository")
        total_files = scan_result.get("total_files", 0)
        total_lines = scan_result.get("total_lines", 0)
        entrypoints = ", ".join(scan_result.get("entrypoint_candidates", [])) or "None identified"

        md = [
            f"# RepoSloth Analysis Report: {repo_name}",
            f"*Generated on: {now_str} via RepoSloth Local AI Explainer*\n",
            "---",
            "## 1. Summary Statistics",
            f"- **Repository Path**: `{scan_result.get('repo_path', '')}`",
            f"- **Analyzed Files**: {total_files}",
            f"- **Total Lines of Code**: {total_lines:,}",
            f"- **Candidate Entrypoints**: `{entrypoints}`",
            f"- **Skipped Credential Files**: {len(scan_result.get('skipped_secret_files', []))}",
            f"- **Skipped Binary Files**: {scan_result.get('skipped_binary_count', 0)}",
            "\n### Language Distribution",
        ]

        for lang, stats in scan_result.get("language_stats", {}).items():
            md.append(f"- **{lang}**: {stats['files']} files ({stats['lines']:,} lines)")

        md.extend([
            "\n---",
            "## 2. AI Architecture & Codebase Overview",
            "> *Note: The following insights are generated by a local open-weight model grounded in repository manifests and source structure.*\n",
            ai_overview if ai_overview else "*No AI overview generated yet.*",
            "\n---",
            "## 3. Maintenance & Complexity Insights (Heuristics)",
        ])

        large_files = scan_result.get("insights", {}).get("large_files", [])
        if large_files:
            md.append("\n### High Line-Count Files (>400 lines)")
            for item in large_files:
                md.append(f"- `{item['path']}`: {item['lines']} lines")
        else:
            md.append("\n- No excessively large source files detected.")

        deep_files = scan_result.get("insights", {}).get("deeply_nested", [])
        if deep_files:
            md.append("\n### Deeply Nested Files (>=4 levels deep)")
            for item in deep_files:
                md.append(f"- `{item}`")

        skipped_secrets = scan_result.get("skipped_secret_files", [])
        if skipped_secrets:
            md.append("\n### Excluded Sensitive Files (Safety Defense)")
            for sec in skipped_secrets:
                md.append(f"- ⚠️ `{sec}` (Ignored from AI analysis to prevent leakage)")

        md.extend([
            "\n---",
            "## 4. Groundedness & Security Disclosure",
            "- **Execution Safety**: RepoSloth never executes or runs untrusted repository code.",
            "- **Local Privacy**: AI analysis runs via local Ollama. Source code is never transmitted externally.",
            "- **Prompt Injection Shield**: Source code is ingested strictly as data literals."
        ])

        return "\n".join(md)

    @staticmethod
    def generate_file_explanation_report(rel_file_path: str, explanation: str) -> str:
        """Formats single-file explanation for download."""
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        return (
            f"# RepoSloth File Deep-Dive: `{rel_file_path}`\n"
            f"*Generated on: {now_str}*\n\n"
            f"---\n\n"
            f"{explanation}\n\n"
            f"---\n"
            f"*Generated locally with RepoSloth & Open-Weight LLM*\n"
        )
